/**
 * Capture AdminBoard stills for docs filmstrips.
 *
 * Requires live demo (default http://127.0.0.1:9100) and Playwright
 * from packages/admin/web.
 *
 * Usage (from repo root):
 *   node scripts/capture-docs-media.mjs
 *   ADMINBOARD_BASE_URL=http://127.0.0.1:9100 node scripts/capture-docs-media.mjs
 */
import { createRequire } from "node:module";
import { mkdir, copyFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const adminWeb = path.join(root, "packages/admin/web");
const require = createRequire(path.join(adminWeb, "package.json"));

/** @type {typeof import('@playwright/test')} */
const { chromium } = require("@playwright/test");

const baseURL = process.env.ADMINBOARD_BASE_URL || "http://127.0.0.1:9100";
const outCanonical = path.join(root, "media/docs/adminboard");
const outPublic = path.join(root, "sites/web/public/media/docs/adminboard");

async function shot(page, name, fullPage = false) {
  const file = `${name}.png`;
  const dest = path.join(outCanonical, file);
  await page.screenshot({ path: dest, fullPage, type: "png" });
  await copyFile(dest, path.join(outPublic, file));
  console.log("wrote", path.relative(root, dest));
}

async function main() {
  await mkdir(outCanonical, { recursive: true });
  await mkdir(outPublic, { recursive: true });

  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({
    viewport: { width: 1280, height: 800 },
    deviceScaleFactor: 1,
  });

  try {
    await page.goto(`${baseURL}/admin/`, { waitUntil: "networkidle" });
    await page.getByTestId("login-page").waitFor({ timeout: 20_000 });
    await shot(page, "01-login");

    await page.getByTestId("login-username").fill("admin");
    await page.getByTestId("login-password").fill("phzyx");
    await page.getByTestId("login-submit").click();
    await page.getByTestId("overview-page").waitFor({ timeout: 20_000 });
    await page.waitForTimeout(400);
    await shot(page, "02-overview");

    await page.getByTestId("nav-users").click();
    await page.getByTestId("resource-page-users").waitFor({ timeout: 15_000 });
    await page.getByTestId("resource-table").waitFor({ timeout: 10_000 });
    await page.waitForTimeout(400);
    await shot(page, "03-users-table");

    await page.getByTestId("table-row").first().click();
    await page.getByTestId("record-drawer").waitFor({ timeout: 10_000 });
    await page.waitForTimeout(300);
    await shot(page, "04-record-drawer");

    // Close drawer if close control exists; otherwise navigate away
    const close = page.getByTestId("drawer-close");
    if (await close.count()) {
      await close.click().catch(() => {});
    } else {
      await page.keyboard.press("Escape").catch(() => {});
    }
    await page.waitForTimeout(200);

    await page.getByTestId("nav-media").click();
    await page.getByTestId("media-page").waitFor({ timeout: 15_000 });
    await page.waitForTimeout(500);
    await shot(page, "05-media-library");

    const manifest = {
      capturedAt: new Date().toISOString(),
      baseURL,
      shots: [
        "01-login.png",
        "02-overview.png",
        "03-users-table.png",
        "04-record-drawer.png",
        "05-media-library.png",
      ],
      note: "Generated by scripts/capture-docs-media.mjs — re-run after SPA UI changes.",
    };
    await writeFile(
      path.join(outCanonical, "manifest.json"),
      JSON.stringify(manifest, null, 2) + "\n",
    );
    await copyFile(
      path.join(outCanonical, "manifest.json"),
      path.join(outPublic, "manifest.json"),
    );
    console.log("OK — AdminBoard media pack ready");
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
