ADMIN_MODULE = '''\
"""AdminBoard wiring generated by ``phzyx new`` / ``phzyx add admin``.

Install: ``uv add phzyx-admin-fastapi``
Optional authz: ``from app.auth import authz_for_admin`` (when auth is present).
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from phzyx.admin.fastapi import AdminBoard
from phzyx.orm.session_sync import Session

SessionFactory = Callable[[], Session]


def mount_admin(
    app: Any,
    *,
    models: Sequence[type],
    session_factory: SessionFactory,
    theme: str = "magical-white",
    storage_root: Path | None = None,
    authz: Any = None,
    prefix: str = "/admin",
) -> AdminBoard:
    """Mount AdminBoard on a FastAPI app."""
    return AdminBoard(
        app,
        models=list(models),
        session_factory=session_factory,
        theme=theme,
        storage_root=storage_root,
        authz=authz,
        prefix=prefix,
    )
'''

ADMIN_README = """\
# AdminBoard

Generated by `phzyx add admin` / `phzyx new --preset max|full`.

## Setup

```bash
uv add phzyx-admin-fastapi
```

## FastAPI

```python
from fastapi import FastAPI
from app.admin_board import mount_admin
from app.models import MODELS  # your models list

app = FastAPI()
# session_factory: () -> phzyx.orm.Session
mount_admin(app, models=MODELS, session_factory=session_factory)
```

Open `/admin/` after starting uvicorn. With auth:

```python
from app.auth import authz_for_admin, install_auth

install_auth(app, session_factory)
mount_admin(app, models=MODELS, session_factory=session_factory, authz=authz_for_admin())
```
"""


def _validate_name(name: str) -> str:
    name = name.strip()
    if not name or not _NAME_RE.match(name):
        raise ValueError(
            f"invalid project name {name!r}: use letters, digits, _ or - (must start with a letter)"
        )
    return name


def _layout_paths(
    root: Path,
    layout: str,
    *,
    auth: bool,
    admin: bool,
) -> dict[Path, str]:
    """Map relative destination paths → file contents for a layout."""
    files: dict[Path, str] = {}
    layout = layout.lower().strip()
    if layout not in LAYOUT_NAMES:
        raise ValueError(f"unknown layout {layout!r}; choose one of: {', '.join(LAYOUT_NAMES)}")

    if layout == "flat":
        app = root / "app"
        files[app / "__init__.py"] = _package_init()
        files[app / "main.py"] = ""  # filled by caller with title
        files[app / "models.py"] = _models_stub()
        if auth:
            files[app / "auth.py"] = AUTH_MODULE
        if admin:
            files[app / "admin_board.py"] = ADMIN_MODULE

    elif layout == "mvc":
        app = root / "app"
        files[app / "__init__.py"] = _package_init()
        files[app / "main.py"] = ""
        files[app / "models" / "__init__.py"] = _models_stub()
        files[app / "views" / "__init__.py"] = _mvc_views()
        files[app / "controllers" / "__init__.py"] = _mvc_controllers()
        if auth:
            files[app / "auth.py"] = AUTH_MODULE
        if admin:
            files[app / "admin_board.py"] = ADMIN_MODULE

    elif layout == "clean":
        files[root / "domain" / "__init__.py"] = _clean_domain()
        files[root / "domain" / "models.py"] = _models_stub()
        files[root / "application" / "__init__.py"] = _clean_application()
        files[root / "infrastructure" / "__init__.py"] = _clean_infrastructure()
        app = root / "app"
        files[app / "__init__.py"] = _package_init()
        files[app / "main.py"] = ""
        if auth:
            files[root / "infrastructure" / "auth.py"] = AUTH_MODULE
        if admin:
            files[root / "infrastructure" / "admin_board.py"] = ADMIN_MODULE

    elif layout == "phzyx-app":
        app = root / "app"
        files[app / "__init__.py"] = _package_init()
        files[app / "main.py"] = ""
        files[app / "models.py"] = _models_stub()
        files[root / "packages" / ".gitkeep"] = ""
        files[root / "packages" / "README.md"] = (
            "# Local packages\n\nOptional workspace members (domain libs, shared code).\n"
        )
        if auth:
            files[app / "auth.py"] = AUTH_MODULE
        if admin:
            files[app / "admin_board.py"] = ADMIN_MODULE

    return files


def plan_new(
    name: str,
    *,
    preset: str = DEFAULT_PRESET,
    layout: str = DEFAULT_LAYOUT,
    parent: Path | None = None,
) -> list[tuple[Path, str]]:
    """Return ordered ``(path, content)`` pairs that would be written."""
    name = _validate_name(name)
    spec = get_preset(preset)
    parent = (parent or Path.cwd()).resolve()
    root = parent / name

    auth = bool(spec.get("auth"))
    admin = bool(spec.get("admin"))
    packages: list[str] = list(spec.get("packages") or [])

    layout_files = _layout_paths(root, layout, auth=auth, admin=admin)
    # Fill main.py with real stub
    main_content = _main_flat(title=name, auth=auth, admin=admin)
    for path in list(layout_files):
        if path.name == "main.py" and layout_files[path] == "":
            layout_files[path] = main_content

    planned: list[tuple[Path, str]] = [
        (root / "pyproject.toml", _pyproject(name, packages)),
        (root / "README.md", _readme(name, preset, layout, auth=auth, admin=admin)),
        (root / ".gitignore", _gitignore()),
    ]
    if spec.get("env_example"):
        planned.append((root / ".env.example", _env_example(auth=auth)))
    if auth:
        planned.append((root / "AUTH.md", AUTH_README))
    if admin:
        planned.append((root / "ADMIN.md", ADMIN_README))
    if spec.get("docker"):
        planned.append((root / "docker-compose.yml", _docker_compose()))

    # layout files after root docs
    for path, content in sorted(layout_files.items(), key=lambda x: str(x[0])):
        planned.append((path, content))
    return planned


def new_project(
    name: str,
    *,
    preset: str = DEFAULT_PRESET,
    layout: str = DEFAULT_LAYOUT,
    parent: Path | None = None,
    force: bool = False,
    dry_run: bool = False,
) -> list[Path]:
    """Create project scaffold. Returns paths written (or that would be).

    Raises
    ------
    ValueError
        Invalid name, preset, or layout.
    FileExistsError
        Target exists and is non-empty without ``force``.
    """
    planned = plan_new(name, preset=preset, layout=layout, parent=parent)
    if not planned:
        return []

    # First planned path is always <project>/pyproject.toml
    project_root = planned[0][0].parent
    if project_root.exists() and any(project_root.iterdir()) and not force:
        raise FileExistsError(f"refusing to write into non-empty {project_root} (use --force)")

    written: list[Path] = []
    for path, content in planned:
        if dry_run:
            written.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and not force:
            raise FileExistsError(f"refusing to overwrite {path} (use --force)")
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written
