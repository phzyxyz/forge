"""``phzyx new`` — scaffold a Phzyx project from preset + layout."""

from __future__ import annotations

import re
from pathlib import Path

from phzyx.cli.add_auth import AUTH_MODULE
from phzyx.cli.add_auth import README_SNIPPET as AUTH_README
from phzyx.cli.presets import (
    DEFAULT_LAYOUT,
    DEFAULT_PRESET,
    LAYOUT_NAMES,
    get_preset,
)

_NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")


def _pyproject(name: str, packages: list[str]) -> str:
    deps = ",\n".join(f'  "{p}"' for p in packages)
    return f'''\
[project]
name = "{name}"
version = "0.1.0"
description = "Phzyx app scaffolded by phzyx new"
requires-python = ">=3.11"
dependencies = [
{deps},
]

[tool.uv]
package = false
'''


def _readme(name: str, preset: str, layout: str, *, auth: bool, admin: bool) -> str:
    lines = [
        f"# {name}",
        "",
        f"Scaffolded by `phzyx new` (preset **{preset}**, layout **{layout}**).",
        "",
        "## Setup",
        "",
        "```bash",
        "uv sync",
    ]
    if auth:
        lines.append(
            "export PHZYX_AUTH_SECRET=\"$(python -c 'import secrets; "
            "print(secrets.token_urlsafe(32))')\""
        )
    lines.extend(
        [
            "uv run uvicorn app.main:app --reload",
            "```",
            "",
            "## Next",
            "",
            "- `phzyx doctor` — security / import checks",
        ]
    )
    if auth:
        lines.append("- `phzyx add auth` already applied if you used normal+")
        lines.append("- `phzyx auth create-superuser` after pushing auth models")
    if admin:
        lines.append("- AdminBoard at `/admin/` (see `app/admin_board.py`)")
    else:
        lines.append("- `phzyx add admin` to wire AdminBoard later")
    lines.append("")
    return "\n".join(lines)


def _env_example(*, auth: bool) -> str:
    lines = [
        "# Copy to .env and fill in (never commit secrets)",
        "PHZYX_DATABASE_URL=sqlite:///./app.db",
        "PHZYX_ENV=development",
    ]
    if auth:
        lines.extend(
            [
                "PHZYX_AUTH_SECRET=replace-with-secrets-token-urlsafe-32+",
                "PHZYX_AUTH_PRODUCTION=0",
                "# PHZYX_AUTH_COOKIE_SECURE=1  # force secure cookies",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def _gitignore() -> str:
    return """\
.env
.venv/
__pycache__/
*.py[cod]
.pytest_cache/
.mypy_cache/
*.db
.DS_Store
"""


def _main_flat(*, title: str, auth: bool, admin: bool) -> str:
    auth_import = ""
    auth_wire = ""
    if auth:
        auth_import = "from app.auth import install_auth  # noqa: F401\n"
        auth_wire = (
            "\n# Wire auth after you have a session_factory:\n"
            "# install_auth(app, session_factory)\n"
        )
    admin_import = ""
    admin_wire = ""
    if admin:
        admin_import = "from app.admin_board import mount_admin  # noqa: F401\n"
        admin_wire = (
            "\n# Wire AdminBoard after models + session_factory:\n"
            "# mount_admin(app, models=[...], session_factory=session_factory)\n"
        )
    return f'''\
"""FastAPI entry — generated by ``phzyx new``."""

from __future__ import annotations

from fastapi import FastAPI
{auth_import}{admin_import}
app = FastAPI(title="{title}", version="0.1.0")
{auth_wire}{admin_wire}

@app.get("/")
def root() -> dict[str, str]:
    return {{"message": "hello from {title}", "status": "scaffold"}}


@app.get("/health")
def health() -> dict[str, str]:
    return {{"status": "ok"}}
'''


def _models_stub() -> str:
    return '''\
"""Example models — replace with your domain."""

from __future__ import annotations

from phzyx.orm import Field, Model


class Item(Model):
    id: int = Field(primary_key=True)
    name: str = Field()

    class Meta:
        table = "items"
        register = False


MODELS = [Item]
'''


