"""Enums, unique_together, checks, max_length VARCHAR."""

from __future__ import annotations

from enum import StrEnum

import pytest
from phzyx.schema import Dialect, Field, Model, build_manifest, render_create_table


class Status(StrEnum):
    draft = "draft"
    live = "live"


class Article(Model):
    id: int | None = Field(default=None, primary_key=True)
    tenant_id: int = Field()
    slug: str = Field(max_length=64)
    status: Status = Field(default=Status.draft)
    age: int = Field(default=0)

    class Meta:
        table = "articles"
        register = False
        unique_together = [("tenant_id", "slug")]
        checks = ["age >= 0"]


@pytest.mark.unit
def test_enum_check_unique_together_varchar() -> None:
    m = build_manifest([Article])
    t = m.table("articles")
    slug = next(c for c in t.columns if c.name == "slug")
    assert slug.db_type == "VARCHAR(64)" or slug.max_length == 64
    status = next(c for c in t.columns if c.name == "status")
    assert status.enum_values == ("draft", "live")
    assert any(i.unique and i.columns == ("tenant_id", "slug") for i in t.indexes)
    assert any(c.kind == "check" and c.expression and "age" in c.expression for c in t.constraints)
    assert any(
        c.kind == "check" and c.expression and "draft" in (c.expression or "")
        for c in t.constraints
    )

    pg = render_create_table(t, Dialect.POSTGRES)
    assert "VARCHAR(64)" in pg
    assert "CHECK" in pg
    assert "GENERATED BY DEFAULT AS IDENTITY" in pg

    sq = render_create_table(t, Dialect.SQLITE)
    assert "INTEGER PRIMARY KEY" in sq
    assert "CHECK" in sq
