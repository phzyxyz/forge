"""Autoincrement PK + timestamp defaults on insert."""

from __future__ import annotations

from datetime import datetime

import pytest
from phzyx.orm import Field, Model, Session
from phzyx.schema import Dialect, apply_manifest_sqlite, build_manifest
from phzyx.schema.types import Dialect as D


class User(Model):
    id: int | None = Field(default=None, primary_key=True)
    email: str = Field(unique=True)
    created_at: datetime | None = Field(default=None, auto_now_add=True)

    class Meta:
        table = "ai_users"
        register = False


@pytest.mark.unit
def test_sqlite_autoincrement_and_auto_now_add() -> None:
    m = build_manifest([User])
    sql = __import__("phzyx.schema.ddl", fromlist=["render_create_table"]).render_create_table(
        m.table("ai_users"), Dialect.SQLITE
    )
    assert "INTEGER PRIMARY KEY" in sql
    assert "GENERATED" not in sql

    conn = apply_manifest_sqlite(m)
    session = Session(conn, dialect=D.SQLITE)
    u = session.add(User(email="a@b.co"))
    session.commit()
    assert u.id == 1
    assert isinstance(u.created_at, datetime)

    u2 = session.add(User(email="c@d.co"))
    session.commit()
    assert u2.id == 2


@pytest.mark.unit
def test_postgres_ddl_identity() -> None:
    from phzyx.schema.ddl import render_create_table

    m = build_manifest([User])
    sql = render_create_table(m.table("ai_users"), Dialect.POSTGRES)
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
